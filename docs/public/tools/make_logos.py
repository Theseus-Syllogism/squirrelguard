#!/usr/bin/env python3
"""Software marks for the public documents: brand logos and letter tiles, as small SVG files in img/logos/.

    python3 docs/public/tools/make_logos.py            # letter tiles only (no network)
    python3 docs/public/tools/make_logos.py --fetch    # also download the brand logos again

Brand logos come from Simple Icons (https://simpleicons.org, CC0-1.0), one path each, coloured with the brand
colour that project records. They are trademarks of their owners and are used only to identify the software.
Software without a logo there gets a letter tile in a neutral colour, so it cannot be mistaken for a brand mark.
"""
import pathlib
import subprocess
import sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "img" / "logos"
SIMPLE_ICONS = "13.21.0"
INK = "1B1F24"

# file name -> (Simple Icons slug, fill colour). Very light or black brand colours are drawn in ink.
BRANDS = {
    "docker": ("docker", "2496ED"), "postgresql": ("postgresql", "4169E1"), "python": ("python", "3776AB"),
    "nginx": ("nginx", "009639"), "grafana": ("grafana", "F46800"), "mosquitto": ("eclipsemosquitto", "3C5280"),
    "onnx": ("onnx", "005CED"), "opencv": ("opencv", "5C3EE8"), "flask": ("flask", INK),
    "threejs": ("threedotjs", INK), "authelia": ("authelia", "113155"), "letsencrypt": ("letsencrypt", "003A70"),
    "uptimekuma": ("uptimekuma", "3BA55D"), "ffmpeg": ("ffmpeg", "007808"), "nvidia": ("nvidia", "76B900"),
    "intel": ("intel", "0071C5"), "openssl": ("openssl", "721412"), "ntfy": ("ntfy", "317F6F"),
    "linux": ("linux", INK), "bash": ("gnubash", "3E8E1F"), "mqtt": ("mqtt", "660066"),
    "git": ("git", "F03C2E"),
    "toml": ("toml", "9C4121"), "markdown": ("markdown", INK), "drawio": ("diagramsdotnet", "F08705"),
    "mediapipe": ("mediapipe", "0097A7"), "pytorch": ("pytorch", "EE4C2C"), "json": ("json", INK),
    "curl": ("curl", "073551"), "numpy": ("numpy", "013243"),
}

# file name -> letters. Software with no logo in Simple Icons.
TILES = {
    "frigate": "Fr", "go2rtc": "g2", "suricata": "Su", "llamacpp": "ll", "openvino": "OV", "thingino": "Th",
    "ultralytics": "YO", "qwen": "Qw", "lego": "le", "onnxruntime": "OR", "squirrel-guard": "sg",
    "tensorrt": "RT", "systemd": "sd",
}
TILE_FILL = "44546A"


def tile(letters: str) -> str:
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" role="img">'
            f'<rect x="1" y="1" width="22" height="22" rx="5" fill="#{TILE_FILL}"/>'
            f'<text x="12" y="16.2" text-anchor="middle" font-family="Inter, Helvetica, Arial, sans-serif" '
            f'font-size="11" font-weight="700" fill="#fff">{letters}</text></svg>\n')


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for name, letters in TILES.items():
        (OUT / f"{name}.svg").write_text(tile(letters))
    if "--fetch" in sys.argv:
        for name, (slug, colour) in BRANDS.items():
            url = f"https://cdn.jsdelivr.net/npm/simple-icons@{SIMPLE_ICONS}/icons/{slug}.svg"
            r = subprocess.run(["curl", "-fsS", "-m", "20", url], capture_output=True, text=True)
            if r.returncode != 0 or "<svg" not in r.stdout:      # a logo that is gone upstream: keep the old file
                print(f"skip {name}: {r.stderr.strip() or 'not an SVG'}")
                continue
            svg = r.stdout
            svg = svg.replace("<svg ", f'<svg width="24" height="24" fill="#{colour}" ', 1)
            (OUT / f"{name}.svg").write_text(svg + "\n")
    (OUT / "README.txt").write_text(
        "Brand logos: Simple Icons " + SIMPLE_ICONS + " (https://simpleicons.org), CC0-1.0. Each logo is a trademark of\n"
        "its owner and is used here only to identify the software; no endorsement is implied.\n"
        "Letter tiles (grey squares with two letters) are generated by tools/make_logos.py for software that has\n"
        "no logo in that collection; they are not brand marks.\n")
    print(f"{len(list(OUT.glob('*.svg')))} marks in {OUT}")


if __name__ == "__main__":
    main()
